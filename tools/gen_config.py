#!/usr/bin/env python3
"""Generate both config files from `ftl.yaml`."""

# Only the project's own YAML subset is read: two-space indentation,
# `key: value`, `#` comments, integers and plain decimals. Anything else is an
# error with a file and line, so a typo cannot silently change a compiled
# constant. Standard library only.
#
# `--check` writes nothing. It compares the files on disk with what would be
# generated and exits non-zero with a diff when either differs.

import difflib
import re
import sys
from pathlib import Path

SOURCE = Path("ftl.yaml")
GENERATED_RUST = Path("src/ftl_config.rs")
GENERATED_HEADER = Path("include/ftl-config.h")

RUST_BANNER = (
    "// @generated by tools/gen_config.py from ftl.yaml. Do not edit."
)
C_BANNER = (
    "/* @generated by tools/gen_config.py from ftl.yaml. Do not edit. */"
)

BACKENDS = ("ramdisk", "zone", "bluedbm", "raspberry", "default")
BIT_FIELDS = ("bus_bits", "chip_bits", "page_bits", "block_bits")
GEOMETRY_FIELDS = BIT_FIELDS + ("page_size",)
TUNING_FIELDS = ("gc_ratio", "gc_all", "gc_threshold")

# The Rust geometry arms. The no-feature arm selects the ramdisk section, and
# `default` is only the C header's fallback.
RUST_ARMS = (
    ("zone", 'feature = "zone"'),
    ("bluedbm", 'feature = "bluedbm"'),
    ("raspberry", 'feature = "raspberry"'),
)
RUST_DEFAULT_SECTION = "ramdisk"
RUST_DEFAULT_CFG = (
    'not(any(feature = "zone", feature = "bluedbm", feature = "raspberry"))'
)

GEOMETRY_CONSTANTS = (
    ("DEVICE_NR_BUS_BITS", "bus_bits", "u32", "bus (channel) address bits"),
    ("DEVICE_NR_CHIPS_BITS", "chip_bits", "u32", "chip (way) address bits"),
    ("DEVICE_NR_PAGES_BITS", "page_bits", "u32", "page address bits"),
    ("DEVICE_NR_BLOCKS_BITS", "block_bits", "u32", "block address bits"),
    ("DEVICE_PAGE_SIZE", "page_size", "usize", "device page size in bytes"),
)

C_MACROS = {
    "bus_bits": "DEVICE_NR_BUS_BITS",
    "chip_bits": "DEVICE_NR_CHIPS_BITS",
    "page_bits": "DEVICE_NR_PAGES_BITS",
    "block_bits": "DEVICE_NR_BLOCKS_BITS",
    "page_size": "DEVICE_PAGE_SIZE",
}

TUNING_DOCS = {
    "gc_ratio": (
        "/// Maximum fraction of the segments one GC pass collects, C's\n"
        "/// `PAGE_FTL_GC_RATIO`."
    ),
    "gc_all": "/// Collect every dirty segment, C's `PAGE_FTL_GC_ALL`.",
    "gc_threshold": (
        "/// GC triggers once the free-page fraction drops below this, C's\n"
        "/// `PAGE_FTL_GC_THRESHOLD`."
    ),
}

_KEY_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
_INT_RE = re.compile(r"-?(?:0|[1-9][0-9]*)\Z")
_DECIMAL_RE = re.compile(r"-?(?:0|[1-9][0-9]*)\.[0-9]+\Z")


class ConfigError(Exception):
    """A grammar or value error, tagged with its file and line."""

    def __init__(self, path, line, message):
        """Tag a message with the source file and line."""
        super().__init__(f"{path}:{line}: {message}")


def _line_of(where, key):
    return where.get(key, 1)


def _parse_scalar(path, line, value):
    if _INT_RE.match(value):
        return int(value)
    if _DECIMAL_RE.match(value):
        return float(value)
    if value and value[0] in "\"'{[&*!|>%@`":
        raise ConfigError(path, line, f"unsupported YAML syntax {value[0]!r}")
    raise ConfigError(
        path, line, f"{value!r} is not an integer or plain decimal"
    )


def parse(text, path=SOURCE.name):
    """Parse the subset grammar into nested dicts, plus a path to line map."""
    data = {}
    where = {}
    stack = [(-2, "", data)]

    for line, raw in enumerate(text.splitlines(), 1):
        if "\t" in raw:
            raise ConfigError(path, line, "tab character, use spaces")
        body = raw.split("#", 1)[0]
        if not body.strip():
            continue
        stripped = body.lstrip(" ")
        indent = len(body) - len(stripped)
        if indent % 2:
            raise ConfigError(
                path, line, "indentation must be two spaces per level"
            )
        if stripped[0] in "\"'{[&*!|>%@`":
            raise ConfigError(
                path, line, f"unsupported YAML syntax {stripped[0]!r}"
            )

        is_section = stripped.endswith(":")
        if is_section:
            key = stripped[:-1]
            if not _KEY_RE.match(key):
                raise ConfigError(path, line, f"invalid key {key!r}")
            value = None
        else:
            if ":" not in stripped:
                raise ConfigError(path, line, "expected 'key: value'")
            key, value = stripped.split(":", 1)
            key = key.rstrip()
            if not _KEY_RE.match(key):
                raise ConfigError(path, line, f"invalid key {key!r}")
            value = value.strip()
            if not value:
                raise ConfigError(path, line, f"missing value for {key!r}")

        while stack[-1][0] >= indent:
            stack.pop()
        parent_indent, prefix, parent = stack[-1]
        if indent != parent_indent + 2:
            raise ConfigError(
                path,
                line,
                "expected one more indentation level than the parent",
            )
        if key in parent:
            raise ConfigError(path, line, f"duplicate key {key!r}")

        dotted = f"{prefix}{key}"
        where[dotted] = line
        if is_section:
            child = {}
            parent[key] = child
            stack.append((indent, dotted + ".", child))
        else:
            parent[key] = _parse_scalar(path, line, value)

    return data, where


def _require_keys(mapping, expected, prefix, where, path, section_name):
    for key in expected:
        if key not in mapping:
            raise ConfigError(
                path,
                _line_of(where, prefix.rstrip(".")),
                f"missing key {key!r} in {section_name}",
            )
    for key in mapping:
        if key not in expected:
            raise ConfigError(
                path,
                _line_of(where, f"{prefix}{key}"),
                f"unknown key {key!r} in {section_name}",
            )


def validate(data, where, path=SOURCE.name):
    """Check the shape and the values, raising `ConfigError` on a violation."""
    _require_keys(
        data, ("tuning", "geometry"), "", where, path, "the top level"
    )

    tuning = data["tuning"]
    if not isinstance(tuning, dict):
        raise ConfigError(
            path, _line_of(where, "tuning"), "'tuning' must be a section"
        )
    _require_keys(tuning, TUNING_FIELDS, "tuning.", where, path, "tuning")
    for key in TUNING_FIELDS:
        value = tuning[key]
        if isinstance(value, dict):
            raise ConfigError(
                path,
                _line_of(where, f"tuning.{key}"),
                f"tuning.{key} must be a number",
            )
        if not 0.0 < float(value) <= 1.0:
            raise ConfigError(
                path,
                _line_of(where, f"tuning.{key}"),
                f"tuning.{key} must be in (0.0, 1.0], got {value}",
            )

    geometry = data["geometry"]
    if not isinstance(geometry, dict):
        raise ConfigError(
            path, _line_of(where, "geometry"), "'geometry' must be a section"
        )
    _require_keys(geometry, BACKENDS, "geometry.", where, path, "geometry")
    for backend in BACKENDS:
        section = geometry[backend]
        prefix = f"geometry.{backend}."
        if not isinstance(section, dict):
            raise ConfigError(
                path,
                _line_of(where, f"geometry.{backend}"),
                f"'geometry.{backend}' must be a section",
            )
        _require_keys(section, GEOMETRY_FIELDS, prefix, where, path, backend)
        for field in BIT_FIELDS:
            value = section[field]
            if isinstance(value, dict) or not isinstance(value, int):
                raise ConfigError(
                    path,
                    _line_of(where, prefix + field),
                    f"{prefix}{field} must be an integer",
                )
            if not 1 <= value <= 31:
                raise ConfigError(
                    path,
                    _line_of(where, prefix + field),
                    f"{prefix}{field} must be in 1..=31, got {value}",
                )
        total = sum(section[field] for field in BIT_FIELDS)
        if total > 32:
            raise ConfigError(
                path,
                _line_of(where, prefix + "block_bits"),
                f"{prefix[:-1]} address needs {total} bits, but "
                "`struct device_address` is one uint32",
            )
        page_size = section["page_size"]
        if isinstance(page_size, dict) or not isinstance(page_size, int):
            raise ConfigError(
                path,
                _line_of(where, prefix + "page_size"),
                f"{prefix}page_size must be an integer",
            )
        if page_size <= 0 or page_size & (page_size - 1):
            raise ConfigError(
                path,
                _line_of(where, prefix + "page_size"),
                f"{prefix}page_size must be a power of two, got {page_size}",
            )

    return data


def read_config(path):
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    data, where = parse(text, path.name)
    return validate(data, where, path.name)


def _rust_float(value):
    text = repr(float(value))
    return text


def render_rust(config):
    lines = [
        RUST_BANNER,
        "",
        "// Cargo features are additive, so two backend features at once would",
        "// define every geometry constant twice with different values. Name",
        "// the mistake here instead of a duplicate-item error that hides it.",
        "#[cfg(any(",
        '    all(feature = "zone", feature = "bluedbm"),',
        '    all(feature = "zone", feature = "raspberry"),',
        '    all(feature = "bluedbm", feature = "raspberry")',
        "))]",
        "compile_error!(",
        '    "enable at most one of zone, bluedbm and raspberry"',
        ");",
    ]

    tuning = config["tuning"]
    lines += ["", "// The page FTL's GC tuning values."]
    for key, name in (
        ("gc_ratio", "PAGE_FTL_GC_RATIO"),
        ("gc_all", "PAGE_FTL_GC_ALL"),
        ("gc_threshold", "PAGE_FTL_GC_THRESHOLD"),
    ):
        lines.append(TUNING_DOCS[key])
        lines.append(
            f"pub const {name}: f64 = {_rust_float(tuning[key])};"
        )

    lines += ["", "// The device geometry. The Rust feature arms mirror the C"]
    lines.append("// header's FTL_BACKEND_* arms.")
    for name, field, kind, description in GEOMETRY_CONSTANTS:
        lines.append("")
        arms = list(RUST_ARMS) + [(RUST_DEFAULT_SECTION, RUST_DEFAULT_CFG)]
        for section, cfg in arms:
            value = config["geometry"][section][field]
            lines.append(
                f"/// `{name}`: {description}, from `ftl.yaml`'s"
            )
            lines.append(f"/// `{section}` section.")
            lines.append(f"#[cfg({cfg})]")
            lines.append(f"pub const {name}: {kind} = {value};")

    return "\n".join(lines) + "\n"


def _header_arm(lines, config, section):
    for _, field, _, _ in GEOMETRY_CONSTANTS:
        macro = C_MACROS[field]
        value = config["geometry"][section][field]
        lines += [
            f"#ifndef {macro}",
            f"#define {macro} ({value})",
            "#endif",
        ]


def render_header(config):
    lines = [
        C_BANNER,
        "",
        "/**",
        " * @file ftl-config.h",
        " * @brief generated device geometry, sourced from `ftl.yaml`",
        " * @author Gijun Oh",
        " * @version 0.1",
        " * @date 2026-10-20",
        " */",
        "#ifndef FTL_CONFIG_H",
        "#define FTL_CONFIG_H",
        "",
        "/*",
        " * One arm per backend. The Makefile passes exactly one",
        " * -DFTL_BACKEND_<NAME> and a consumer may override any macro with",
        " * its own -D, so every macro keeps its #ifndef guard.",
        " */",
    ]
    arms = ("ramdisk", "zone", "bluedbm", "raspberry")
    for index, section in enumerate(arms):
        directive = "#if" if index == 0 else "#elif"
        lines.append(f"{directive} defined(FTL_BACKEND_{section.upper()})")
        _header_arm(lines, config, section)
    lines.append("#else")
    _header_arm(lines, config, "default")
    lines += ["#endif", "", "#endif", ""]
    return "\n".join(lines)


def _write_if_changed(path, content):
    try:
        if path.read_text(encoding="utf-8") == content:
            return False
    except FileNotFoundError:
        pass
    path.write_text(content, encoding="utf-8")
    return True


def generate(root):
    """Write both generated files, returning the ones that changed."""
    root = Path(root)
    config = read_config(root / SOURCE)
    written = []
    for relative, content in (
        (GENERATED_RUST, render_rust(config)),
        (GENERATED_HEADER, render_header(config)),
    ):
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if _write_if_changed(path, content):
            written.append(str(relative))
    return written


def check(root):
    """Print a diff and return 1 when either generated file is stale."""
    root = Path(root)
    config = read_config(root / SOURCE)
    stale = False
    for relative, content in (
        (GENERATED_RUST, render_rust(config)),
        (GENERATED_HEADER, render_header(config)),
    ):
        path = root / relative
        try:
            on_disk = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            on_disk = ""
        if on_disk == content:
            continue
        stale = True
        sys.stdout.writelines(
            difflib.unified_diff(
                on_disk.splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=str(relative),
                tofile=f"{relative} (generated)",
            )
        )
    if stale:
        print("run `make config` to regenerate", file=sys.stderr)
        return 1
    return 0


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    root = Path(__file__).resolve().parent.parent
    if argv == ["--check"]:
        return check(root)
    if argv:
        print("usage: tools/gen_config.py [--check]", file=sys.stderr)
        return 2
    for relative in generate(root):
        print(f"wrote {relative}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
